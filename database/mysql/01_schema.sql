CREATE DATABASE IF NOT EXISTS medmatch CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE medmatch;

CREATE TABLE roles (
  id TINYINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name ENUM('ADMIN','STAFF') NOT NULL UNIQUE,
  description VARCHAR(255) NOT NULL
);

CREATE TABLE users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  role_id TINYINT UNSIGNED NOT NULL,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id)
);

CREATE TABLE medical_cases (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  case_code VARCHAR(20) NOT NULL UNIQUE,
  patient_age TINYINT UNSIGNED NOT NULL,
  patient_gender ENUM('MALE','FEMALE','OTHER') NOT NULL,
  category VARCHAR(80) NOT NULL,
  symptoms TEXT NOT NULL,
  medical_history TEXT NULL,
  clinical_observations TEXT NOT NULL,
  notes TEXT NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at TIMESTAMP NULL,
  CONSTRAINT chk_patient_age CHECK (patient_age BETWEEN 0 AND 120),
  CONSTRAINT fk_cases_user FOREIGN KEY (created_by) REFERENCES users(id)
);

CREATE TABLE diagnoses (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL UNIQUE,
  description TEXT NULL
);

CREATE TABLE treatments (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(250) NOT NULL UNIQUE,
  description TEXT NOT NULL
);

CREATE TABLE case_diagnoses (
  case_id BIGINT UNSIGNED NOT NULL,
  diagnosis_id BIGINT UNSIGNED NOT NULL,
  is_primary BOOLEAN NOT NULL DEFAULT FALSE,
  diagnosed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (case_id, diagnosis_id),
  CONSTRAINT fk_cd_case FOREIGN KEY (case_id) REFERENCES medical_cases(id) ON DELETE CASCADE,
  CONSTRAINT fk_cd_diagnosis FOREIGN KEY (diagnosis_id) REFERENCES diagnoses(id)
);

CREATE TABLE case_treatments (
  case_id BIGINT UNSIGNED NOT NULL,
  treatment_id BIGINT UNSIGNED NOT NULL,
  started_at DATE NULL,
  outcome VARCHAR(255) NULL,
  PRIMARY KEY (case_id, treatment_id),
  CONSTRAINT fk_ct_case FOREIGN KEY (case_id) REFERENCES medical_cases(id) ON DELETE CASCADE,
  CONSTRAINT fk_ct_treatment FOREIGN KEY (treatment_id) REFERENCES treatments(id)
);

CREATE TABLE search_history (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  query_text TEXT NOT NULL,
  search_type ENUM('KEYWORD','STRUCTURED','SEMANTIC','HYBRID') NOT NULL,
  filters_json JSON NULL,
  result_count SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  execution_ms INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_search_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE audit_logs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NULL,
  action ENUM('CREATE','UPDATE','DELETE','LOGIN','ROLE_CHANGE') NOT NULL,
  entity_type VARCHAR(60) NOT NULL,
  entity_id BIGINT UNSIGNED NULL,
  details JSON NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES users(id)
);
